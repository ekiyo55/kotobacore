# ── 分析 & 集計 ───────────────────────────────────────────────
@dataclass
class CategoryResult:
    name: str
    total: int = 0
    emotion_detected: int = 0
    intent_classified: int = 0
    chunks_generated: int = 0
    rag_keywords_generated: int = 0
    total_chunks: int = 0
    total_keywords: int = 0
    rows: list[dict] = field(default_factory=list)


def run(output_json: Path | None, output_md: Path | None) -> None:
    try:
        from kotobacore import Analyzer
    except ImportError:
        print("ERROR: kotobacore not installed", file=sys.stderr)
        sys.exit(1)

    analyzer = Analyzer()
    results: list[CategoryResult] = []

    total_texts = sum(len(v) for v in CORPUS.values())
    processed = 0

    for cat_name, texts in CORPUS.items():
        cat = CategoryResult(name=cat_name, total=len(texts))
        for text in texts:
            processed += 1
            print(f"\r  [{processed:3d}/{total_texts}] {cat_name[:16]:<16} {text[:30]}...", end="", flush=True)

            try:
                r = analyzer.analyze(text)
                emo = r.emotion
                intent = r.intent
                chunks = r.chunks
                rag = r.rag

                emotion_hit = emo is not None and emo.primary is not None
                intent_hit = intent is not None and intent.label not in (None, "unknown")
                chunks_hit = len(chunks) > 0
                rag_hit = len(rag.keywords) > 0

                if emotion_hit:
                    cat.emotion_detected += 1
                if intent_hit:
                    cat.intent_classified += 1
                if chunks_hit:
                    cat.chunks_generated += 1
                if rag_hit:
                    cat.rag_keywords_generated += 1
                cat.total_chunks += len(chunks)
                cat.total_keywords += len(rag.keywords)

                cat.rows.append({
                    "text": text,
                    "emotion": emo.primary if emo else None,
                    "polarity": emo.polarity if emo else None,
                    "intensity": round(emo.intensity, 3) if emo else 0.0,
                    "intent": intent.label if intent else None,
                    "intent_conf": round(intent.confidence, 3) if intent else 0.0,
                    "chunks": [c.text for c in chunks],
                    "keywords": rag.keywords[:5],
                    "error": None,
                })
            except Exception as e:
                cat.rows.append({"text": text, "error": str(e)})

        results.append(cat)

    print()  # newline after progress

    # ── JSON 出力 ──────────────────────────────────────────────
    data = {
        "meta": {
            "date": datetime.now().isoformat(),
            "total": total_texts,
            "categories": len(CORPUS),
        },
        "categories": [],
    }
    for cat in results:
        data["categories"].append({
            "name": cat.name,
            "total": cat.total,
            "emotion_rate": round(cat.emotion_detected / cat.total, 4),
            "intent_rate": round(cat.intent_classified / cat.total, 4),
            "chunk_rate": round(cat.chunks_generated / cat.total, 4),
            "rag_rate": round(cat.rag_keywords_generated / cat.total, 4),
            "avg_chunks": round(cat.total_chunks / cat.total, 2),
            "avg_keywords": round(cat.total_keywords / cat.total, 2),
            "rows": cat.rows,
        })

    if output_json:
        output_json.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
        print(f"JSON saved → {output_json}")

    # ── Markdown 出力 ─────────────────────────────────────────
    md_lines: list[str] = []
    md_lines += [
        "# KotobaCore 500例文 品質テスト結果",
        "",
        f"> 実施日: {datetime.now().strftime('%Y-%m-%d %H:%M')}",
        f"> 総例文数: {total_texts} 件 / カテゴリ数: {len(CORPUS)}",
        "",
        "---",
        "",
        "## 1. 全体サマリー",
        "",
    ]

    # 全体集計
    g_total = sum(c.total for c in results)
    g_emo = sum(c.emotion_detected for c in results)
    g_int = sum(c.intent_classified for c in results)
    g_chk = sum(c.chunks_generated for c in results)
    g_rag = sum(c.rag_keywords_generated for c in results)
    g_chunks = sum(c.total_chunks for c in results)
    g_kws = sum(c.total_keywords for c in results)
    g_err = sum(1 for c in results for r in c.rows if r.get("error"))

    md_lines += [
        "| 指標 | 値 |",
        "|---|---|",
        f"| 総例文数 | {g_total} 件 |",
        f"| 感情検出率 | {g_emo/g_total*100:.1f}% ({g_emo}/{g_total}) |",
        f"| 意図分類率 | {g_int/g_total*100:.1f}% ({g_int}/{g_total}) |",
        f"| チャンク生成率 | {g_chk/g_total*100:.1f}% ({g_chk}/{g_total}) |",
        f"| RAGキーワード生成率 | {g_rag/g_total*100:.1f}% ({g_rag}/{g_total}) |",
        f"| 平均チャンク数 / 文 | {g_chunks/g_total:.2f} |",
        f"| 平均キーワード数 / 文 | {g_kws/g_total:.2f} |",
        f"| エラー件数 | {g_err} 件 |",
        "",
        "---",
        "",
        "## 2. カテゴリ別サマリー",
        "",
        "| カテゴリ | 件数 | 感情検出率 | 意図分類率 | チャンク率 | RAG率 | 平均chunk | 平均kw |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for c in results:
        md_lines.append(
            f"| {c.name} | {c.total} "
            f"| {c.emotion_detected/c.total*100:.0f}% "
            f"| {c.intent_classified/c.total*100:.0f}% "
            f"| {c.chunks_generated/c.total*100:.0f}% "
            f"| {c.rag_keywords_generated/c.total*100:.0f}% "
            f"| {c.total_chunks/c.total:.1f} "
            f"| {c.total_keywords/c.total:.1f} |"
        )

    md_lines += ["", "---", "", "## 3. カテゴリ別詳細", ""]

    for c in results:
        md_lines += [f"### {c.name}", ""]
        md_lines += [
            "| # | テキスト | 感情 | 極性 | 強度 | 意図 | チャンク | キーワード(top5) |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for i, row in enumerate(c.rows, 1):
            if row.get("error"):
                md_lines.append(f"| {i} | {row['text'][:30]} | ERROR | - | - | - | - | {row['error'][:40]} |")
            else:
                chunks_str = " / ".join(row["chunks"][:3]) if row["chunks"] else "-"
                kw_str = " ".join(row["keywords"][:3]) if row["keywords"] else "-"
                md_lines.append(
                    f"| {i} | {row['text'][:28]} "
                    f"| {row['emotion'] or '-'} "
                    f"| {row['polarity'] or '-'} "
                    f"| {row['intensity']:.2f} "
                    f"| {row['intent'] or '-'} "
                    f"| {chunks_str[:24]} "
                    f"| {kw_str[:24]} |"
                )
        md_lines.append("")

    if output_md:
        output_md.write_text("\n".join(md_lines), encoding="utf-8")
        print(f"Markdown saved → {output_md}")

    # ── コンソール表示 ─────────────────────────────────────────
    print("\n" + "=" * 60)
    print("KotobaCore 500例文品質テスト 結果")
    print("=" * 60)
    print(f"{'カテゴリ':<18} {'感情':>6} {'意図':>6} {'chunk':>6} {'RAG':>6} {'avgChunk':>9} {'avgKW':>7}")
    print("-" * 60)
    for c in results:
        print(
            f"{c.name:<18} "
            f"{c.emotion_detected/c.total*100:5.0f}% "
            f"{c.intent_classified/c.total*100:5.0f}% "
            f"{c.chunks_generated/c.total*100:5.0f}% "
            f"{c.rag_keywords_generated/c.total*100:5.0f}% "
            f"{c.total_chunks/c.total:9.2f} "
            f"{c.total_keywords/c.total:7.2f}"
        )
    print("-" * 60)
    print(
        f"{'全体':<18} "
        f"{g_emo/g_total*100:5.0f}% "
        f"{g_int/g_total*100:5.0f}% "
        f"{g_chk/g_total*100:5.0f}% "
        f"{g_rag/g_total*100:5.0f}% "
        f"{g_chunks/g_total:9.2f} "
        f"{g_kws/g_total:7.2f}"
    )
    print(f"\nエラー件数: {g_err}")
    print("=" * 60)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="KotobaCore 500例文品質テスト")
    parser.add_argument("--json", metavar="FILE", help="JSON出力先")
    parser.add_argument("--md", metavar="FILE", help="Markdown出力先", default="/tmp/quality_test_result.md")
    args = parser.parse_args()

    run(
        output_json=Path(args.json) if args.json else None,
        output_md=Path(args.md) if args.md else None,
    )
